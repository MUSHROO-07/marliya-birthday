-- Marliya birthday wish wall
-- Public visitors may submit notes, but only approved notes are visible publicly.
create table if not exists public.marliya_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 50),
  relationship text not null default 'Other' check (relationship in ('Family','Friend','Cousin','Other')),
  message text not null check (char_length(message) between 1 and 500),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.marliya_wishes enable row level security;

-- Anyone may read approved wishes only.
create policy "Anyone can read approved birthday wishes"
  on public.marliya_wishes for select
  using (approved = true);

-- Anyone may submit a wish; it remains hidden until approved by the owner.
create policy "Anyone can submit a birthday wish"
  on public.marliya_wishes for insert
  with check (
    approved = false
    and char_length(name) between 1 and 50
    and char_length(message) between 1 and 500
    and relationship in ('Family','Friend','Cousin','Other')
  );

-- No public UPDATE/DELETE policy is intentionally provided.
-- To approve a wish: Supabase Dashboard -> Table Editor -> marliya_wishes -> set approved = true.
